package dbengine

import (
	"errors"
	"fmt"
	"strconv"
	"strings"
)

// Plan is what the daemon would run for one lifecycle step, plus an honest note
// when the step cannot be automated on this host.
type Plan struct {
	Commands [][]string
	RunAs    string // OS user the commands must execute as (e.g. "postgres")
	// Env carries credentials for a container engine's administration, where the
	// panel talks TCP to the container as the administrator it created — never as
	// an argument, which the process list would show.
	Env  []string
	Note string
}

// Step is one lifecycle action on a database.
type Step string

const (
	StepProvision Step = "provision"
	StepRotate    Step = "rotate"
	StepSuspend   Step = "suspend"
	StepRestore   Step = "restore"
	StepPurge     Step = "purge"
	StepLimits    Step = "limits"
)

// Resource is what a plan acts on.
type Resource struct {
	Engine  string
	Name    string // engine-side database name
	User    string // engine-side role/user
	Secret  string // password (already generated by the caller)
	Port    int
	MaxConn int
	// AdminHost/AdminPort/AdminSecret are the admin connection a shared Redis
	// needs before it will create a user (PostgreSQL and MySQL are reached
	// through the local socket as root and need nothing here).
	AdminHost   string
	AdminPort   int
	AdminSecret string
	// AdminUser is the account that may create roles and databases: the engine's
	// own `postgres` over a socket on a host install, `barepod_admin` inside a
	// container.
	AdminUser string
	// Mode decides which of those two worlds the plan is written for.
	Mode EngineMode
	// KeyPattern overrides the default "<user>:*" a cache user is scoped to. A cache the deploy
	// wizard wired to a website sets "*": the app prefixes its own keys (Laravel writes
	// "laravel_database_…" and "laravel_cache_…"), so the panel's own prefix would refuse every
	// key the app uses — which is exactly what a re-provision did, and the app answered 500 with
	// "NOPERM … to access a key".
	KeyPattern string
	// MaxMemoryMB is the per-instance Redis memory ceiling in megabytes when StepLimits runs.
	MaxMemoryMB int
}

// PlanFor returns the commands for one step.
//
// SQLite has no commands: its lifecycle is file operations the daemon performs
// itself, so it answers an empty plan and says so.
func PlanFor(step Step, resource Resource) (Plan, error) {
	engine, ok := Lookup(resource.Engine)
	if !ok {
		return Plan{}, fmt.Errorf("dbengine: unknown engine %q", resource.Engine)
	}
	if engine.FileBased {
		return Plan{Note: "SQLite is a file inside the site: the daemon moves it instead of running SQL."}, nil
	}
	if !engine.Automated {
		return Plan{Note: engine.Note}, nil
	}
	if resource.Mode == ModeDocker {
		return dockerAdminPlan(step, engine, resource)
	}

	switch engine.Name {
	case "postgresql":
		return postgresPlan(step, resource)
	case "mysql", "mariadb":
		return mysqlPlan(step, resource)
	case "redis":
		return redisPlan(step, resource)
	case "mongodb":
		// MongoDB speaks no SQL and has no client on the host: the panel administers
		// it through its own driver, so there is no command line to plan here.
		return Plan{Note: "MongoDB is administered by the panel's own driver."}, nil
	}
	return Plan{}, fmt.Errorf("dbengine: no plan for %q", engine.Name)
}

func postgresPlan(step Step, resource Resource) (Plan, error) {
	db := quoteIdent(resource.Name)
	role := quoteIdent(resource.User)
	if resource.Name == "" || resource.User == "" {
		return Plan{}, errors.New("dbengine: a name and a user are required")
	}
	psql := func(sql string) []string {
		cmd := []string{"psql", "-v", "ON_ERROR_STOP=1"}
		if resource.Port != 0 && resource.Port != 5432 {
			cmd = append(cmd, "-p", fmt.Sprint(resource.Port))
		}
		return append(cmd, "-c", sql)
	}

	plan := Plan{RunAs: "postgres"}
	switch step {
	case StepProvision:
		if resource.Secret == "" {
			return Plan{}, errors.New("dbengine: a password is required")
		}
		plan.Commands = [][]string{
			psql(fmt.Sprintf(`CREATE ROLE %s LOGIN PASSWORD %s`, role, quoteLiteral(resource.Secret))),
			psql(fmt.Sprintf(`CREATE DATABASE %s OWNER %s ENCODING 'UTF8'`, db, role)),
		}
		return plan, nil
	case StepRotate:
		if resource.Secret == "" {
			return Plan{}, errors.New("dbengine: a password is required")
		}
		// A rotate must repair a record that outlived its role, not just change a password:
		// ALTER ROLE on a role that no longer exists answers "role does not exist" and the
		// panel surfaced a 502 — the same defect the MySQL plan had. The DO block creates the
		// role when it is missing and is a no-op otherwise.
		plan.Commands = [][]string{
			psql(fmt.Sprintf(`DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = %s) THEN
    CREATE ROLE %s LOGIN PASSWORD %s;
  ELSE
    ALTER ROLE %s WITH LOGIN PASSWORD %s;
  END IF;
END
$$;`,
				quoteLiteral(resource.User), role, quoteLiteral(resource.Secret),
				role, quoteLiteral(resource.Secret))),
		}
		return plan, nil
	case StepSuspend:
		// Refuse new connections and stop the account: the data stays.
		plan.Commands = [][]string{
			psql(fmt.Sprintf(`ALTER DATABASE %s ALLOW_CONNECTIONS false`, db)),
			psql(fmt.Sprintf(`ALTER ROLE %s NOLOGIN`, role)),
		}
		return plan, nil
	case StepRestore:
		plan.Commands = [][]string{
			psql(fmt.Sprintf(`ALTER DATABASE %s ALLOW_CONNECTIONS true`, db)),
			psql(fmt.Sprintf(`ALTER ROLE %s LOGIN`, role)),
		}
		return plan, nil
	case StepPurge:
		plan.Commands = [][]string{
			psql(fmt.Sprintf(`DROP DATABASE IF EXISTS %s WITH (FORCE)`, db)),
			psql(fmt.Sprintf(`DROP ROLE IF EXISTS %s`, role)),
		}
		return plan, nil
	case StepLimits:
		plan.Commands = [][]string{
			psql(fmt.Sprintf(`ALTER ROLE %s CONNECTION LIMIT %d`, role, resource.MaxConn)),
		}
		return plan, nil
	}
	return Plan{}, fmt.Errorf("dbengine: unknown step %q", step)
}

func mysqlPlan(step Step, resource Resource) (Plan, error) {
	if resource.Name == "" || resource.User == "" {
		return Plan{}, errors.New("dbengine: a name and a user are required")
	}
	db := quoteBacktick(resource.Name)
	// The user is scoped to loopback: both unix socket ('localhost') and TCP ('127.0.0.1')
	// so applications, DbGate, phpMyAdmin and Go drivers can all authenticate.
	accountLocal := fmt.Sprintf("'%s'@'localhost'", escapeSingleQuotes(resource.User))
	accountTCP := fmt.Sprintf("'%s'@'127.0.0.1'", escapeSingleQuotes(resource.User))
	client := func(sql string) []string {
		cmd := []string{resource.ClientBinary(), "--no-defaults"}
		if resource.Port != 0 && resource.Port != 3306 {
			cmd = append(cmd, "-P", fmt.Sprint(resource.Port))
		}
		return append(cmd, "-e", sql)
	}

	switch step {
	case StepProvision:
		if resource.Secret == "" {
			return Plan{}, errors.New("dbengine: a password is required")
		}
		return Plan{Commands: [][]string{client(strings.Join([]string{
			fmt.Sprintf("CREATE DATABASE IF NOT EXISTS %s CHARACTER SET utf8mb4", db),
			fmt.Sprintf("CREATE USER IF NOT EXISTS %s IDENTIFIED BY '%s'", accountLocal, escapeSingleQuotes(resource.Secret)),
			fmt.Sprintf("ALTER USER %s IDENTIFIED BY '%s'", accountLocal, escapeSingleQuotes(resource.Secret)),
			fmt.Sprintf("GRANT ALL PRIVILEGES ON %s.* TO %s", db, accountLocal),
			fmt.Sprintf("CREATE USER IF NOT EXISTS %s IDENTIFIED BY '%s'", accountTCP, escapeSingleQuotes(resource.Secret)),
			fmt.Sprintf("ALTER USER %s IDENTIFIED BY '%s'", accountTCP, escapeSingleQuotes(resource.Secret)),
			fmt.Sprintf("GRANT ALL PRIVILEGES ON %s.* TO %s", db, accountTCP),
			"FLUSH PRIVILEGES",
		}, "; "))}}, nil
	case StepRotate:
		if resource.Secret == "" {
			return Plan{}, errors.New("dbengine: a password is required")
		}
		// A rotate has to leave a *usable* record, not just a working account: a ledger row
		// can outlive both its MySQL user and its database. CREATE ... IF NOT EXISTS repairs
		// either and is a no-op when they exist — without it the account logged in to
		// phpMyAdmin and saw "No databases", because the grant pointed at a database that
		// was not there.
		return Plan{Commands: [][]string{client(strings.Join([]string{
			fmt.Sprintf("CREATE DATABASE IF NOT EXISTS %s CHARACTER SET utf8mb4", db),
			fmt.Sprintf("CREATE USER IF NOT EXISTS %s IDENTIFIED BY '%s'", accountLocal, escapeSingleQuotes(resource.Secret)),
			fmt.Sprintf("ALTER USER %s IDENTIFIED BY '%s'", accountLocal, escapeSingleQuotes(resource.Secret)),
			fmt.Sprintf("GRANT ALL PRIVILEGES ON %s.* TO %s", db, accountLocal),
			fmt.Sprintf("CREATE USER IF NOT EXISTS %s IDENTIFIED BY '%s'", accountTCP, escapeSingleQuotes(resource.Secret)),
			fmt.Sprintf("ALTER USER %s IDENTIFIED BY '%s'", accountTCP, escapeSingleQuotes(resource.Secret)),
			fmt.Sprintf("GRANT ALL PRIVILEGES ON %s.* TO %s", db, accountTCP),
			"FLUSH PRIVILEGES",
		}, "; "))}}, nil
	case StepSuspend:
		return Plan{Commands: [][]string{
			client(fmt.Sprintf("REVOKE ALL PRIVILEGES ON %s.* FROM %s; REVOKE ALL PRIVILEGES ON %s.* FROM %s", db, accountLocal, db, accountTCP)),
			client(fmt.Sprintf("ALTER USER %s ACCOUNT LOCK; ALTER USER %s ACCOUNT LOCK", accountLocal, accountTCP)),
			client("FLUSH PRIVILEGES"),
		}}, nil
	case StepRestore:
		return Plan{Commands: [][]string{
			client(fmt.Sprintf("ALTER USER %s ACCOUNT UNLOCK; ALTER USER %s ACCOUNT UNLOCK", accountLocal, accountTCP)),
			client(fmt.Sprintf("GRANT ALL PRIVILEGES ON %s.* TO %s; GRANT ALL PRIVILEGES ON %s.* TO %s", db, accountLocal, db, accountTCP)),
			client("FLUSH PRIVILEGES"),
		}}, nil
	case StepPurge:
		return Plan{Commands: [][]string{
			client(fmt.Sprintf("DROP DATABASE IF EXISTS %s", db)),
			client(fmt.Sprintf("DROP USER IF EXISTS %s, %s", accountLocal, accountTCP)),
		}}, nil
	case StepLimits:
		return Plan{Commands: [][]string{
			client(fmt.Sprintf("ALTER USER %s WITH MAX_USER_CONNECTIONS %d; ALTER USER %s WITH MAX_USER_CONNECTIONS %d", accountLocal, resource.MaxConn, accountTCP, resource.MaxConn)),
		}}, nil
	}
	return Plan{}, fmt.Errorf("dbengine: unknown step %q", step)
}

// RedisDenyDangerous lists the commands an application's cache user never legitimately needs: the
// ones that reach past its own keys, take the server down, read other tenants' traffic, or rewrite
// security. It is an explicit deny list rather than a category so an app keeps everything it really
// uses — notably FLUSHDB, which Laravel's `cache:clear` calls.
//
// Only commands an application has no business calling are denied, and the list is deliberately
// short. What is *not* on it matters as much: KEYS and INFO stay allowed because libraries do call
// them — Laravel's `cache:clear` with a cache prefix runs KEYS inside a Lua script, and health checks
// read INFO. A "safe" list that breaks the app it is protecting is worse than none.
//
// FLUSHDB is left allowed too: it only clears one database index and `php artisan cache:clear` calls
// it. True isolation of it needs a per-app index, which is not done yet (see MASTER_PLAN) — on the
// shared index a flush still clears everyone, so that remains the known gap.
var RedisDenyDangerous = []string{
	"-flushall", "-swapdb", "-restore", "-migrate",
	"-shutdown", "-debug", "-monitor", "-config", "-acl", "-module",
	"-save", "-bgsave", "-bgrewriteaof",
	"-replicaof", "-slaveof", "-failover", "-sync", "-psync", "-replconf",
}

// RedisAppRules is the ACL rule set for an application's cache user: every command, scoped to
// keyPattern, minus RedisDenyDangerous.
func RedisAppRules(keyPattern string) []string {
	rules := []string{"~" + keyPattern, "+@all"}
	return append(rules, RedisDenyDangerous...)
}

// redisPlan drives a shared Redis with ACL users: one user per cache, limited to
// its own key prefix. Suspend turns the user off, restore turns it back on, and
// only purge removes it. Every step is followed by ACL SAVE, so the user survives a
// Redis restart instead of vanishing with the process.
func redisPlan(step Step, resource Resource) (Plan, error) {
	if resource.User == "" {
		return Plan{}, errors.New("dbengine: a user is required")
	}
	prefix := resource.User + ":"
	user := resource.User
	// What the user's keys are scoped to: its own prefix by default, or everything when the caller
	// says the app owns the whole keyspace (a website cache).
	pattern := prefix + "*"
	if resource.KeyPattern != "" {
		pattern = resource.KeyPattern
	}

	// The admin connection: -a carries the password, --no-auth-warning keeps its
	// "using a password with -a" note out of the output we parse.
	base := []string{"redis-cli", "-h", adminHost(resource), "-p", fmt.Sprint(adminPort(resource))}
	if resource.AdminUser != "" {
		base = append(base, "--user", resource.AdminUser)
	}
	if resource.AdminSecret != "" {
		base = append(base, "--no-auth-warning", "-a", resource.AdminSecret)
	}
	run := func(rules ...string) []string {
		return append(append([]string{}, base...), append([]string{"ACL", "SETUSER", user}, rules...)...)
	}
	// ACL changes live in memory until they are written to the aclfile. Without this
	// the user is gone the next time Redis starts — which is how a reboot silently
	// locked an app out of its own cache. Every ACL step ends with it.
	save := append(append([]string{}, base...), "ACL", "SAVE")

	switch step {
	case StepProvision:
		if resource.Secret == "" {
			return Plan{}, errors.New("dbengine: a password is required")
		}
		// "reset" makes the command idempotent, then the user gets exactly its own
		// prefix and every command that cannot reach past it.
		rules := append([]string{"reset", "on", ">" + resource.Secret}, RedisAppRules(pattern)...)
		return Plan{Commands: [][]string{
			run(rules...),
			save,
		}}, nil
	case StepRotate:
		if resource.Secret == "" {
			return Plan{}, errors.New("dbengine: a password is required")
		}
		// "resetpass" first: ACL SETUSER with a new password *adds* one, so without
		// it the old secret would keep working (verified on the host).
		return Plan{Commands: [][]string{
			run("resetpass", ">"+resource.Secret),
			save,
		}}, nil
	case StepSuspend:
		return Plan{Commands: [][]string{run("off"), save}}, nil
	case StepRestore:
		return Plan{Commands: [][]string{run("on"), save}}, nil
	case StepPurge:
		cmd := []string{"redis-cli", "-h", adminHost(resource), "-p", fmt.Sprint(adminPort(resource))}
		if resource.AdminUser != "" {
			cmd = append(cmd, "--user", resource.AdminUser)
		}
		if resource.AdminSecret != "" {
			cmd = append(cmd, "--no-auth-warning", "-a", resource.AdminSecret)
		}
		cmd = append(cmd, "ACL", "DELUSER", user)
		return Plan{
			Commands: [][]string{cmd, save},
			Note:     "The keys under " + prefix + "* are left in place: emptying a cache is not a decision the panel makes for you.",
		}, nil
	case StepLimits:
		memMB := resource.MaxMemoryMB
		if memMB <= 0 {
			memMB = DefaultRedisMaxMemoryMB
		}
		setMem := append(append([]string{}, base...), "CONFIG", "SET", "maxmemory", fmt.Sprintf("%dmb", memMB))
		setPolicy := append(append([]string{}, base...), "CONFIG", "SET", "maxmemory-policy", "allkeys-lru")
		return Plan{Commands: [][]string{setMem, setPolicy}}, nil
	}
	return Plan{}, fmt.Errorf("dbengine: unknown step %q", step)
}

// dockerAdminPlan rewrites the same SQL for a containerised engine, where there is
// no host socket to authenticate against: the panel connects over loopback to the
// engine's container port as the administrator account it created, and the password
// travels in the environment.
func dockerAdminPlan(step Step, engine Engine, resource Resource) (Plan, error) {
	base, err := hostPlanFor(step, engine, resource)
	if err != nil {
		return Plan{}, err
	}
	if len(base.Commands) == 0 {
		return base, nil
	}
	host := resource.AdminHost
	if host == "" {
		host = "127.0.0.1"
	}
	adminUser := resource.AdminUser
	if adminUser == "" {
		return Plan{}, errors.New("dbengine: a container engine needs its administrator account")
	}
	if resource.AdminSecret == "" {
		return Plan{}, errors.New("dbengine: a container engine needs its administrator password")
	}

	plan := Plan{RunAs: "", Note: base.Note}
	for _, argv := range base.Commands {
		statement := lastArgument(argv)
		if statement == "" {
			continue
		}
		switch engine.Name {
		case "postgresql":
			plan.Commands = append(plan.Commands, []string{
				"psql", "-X", "-q", "--no-psqlrc",
				"-h", host, "-p", fmt.Sprint(resource.AdminPort),
				"-U", adminUser, "-d", "postgres", "-c", statement,
			})
		case "mysql", "mariadb":
			plan.Commands = append(plan.Commands, []string{
				engine.Client, "--no-defaults", "--protocol=TCP",
				"-h", host, "-P", fmt.Sprint(resource.AdminPort),
				"-u", adminUser, "-e", statement,
			})
		default:
			return Plan{}, fmt.Errorf("dbengine: no container administration for %q yet", engine.Name)
		}
	}
	switch engine.Name {
	case "postgresql":
		plan.Env = []string{"PGPASSWORD=" + resource.AdminSecret, "PGPASSFILE=/dev/null", "PGCONNECT_TIMEOUT=5"}
	case "mysql", "mariadb":
		plan.Env = []string{"MYSQL_PWD=" + resource.AdminSecret}
	}
	return plan, nil
}

// hostPlanFor is the plan as the host world sees it, without the mode branch.
func hostPlanFor(step Step, engine Engine, resource Resource) (Plan, error) {
	switch engine.Name {
	case "postgresql":
		return postgresPlan(step, resource)
	case "mysql", "mariadb":
		return mysqlPlan(step, resource)
	case "redis":
		return redisPlan(step, resource)
	}
	return Plan{}, fmt.Errorf("dbengine: no plan for %q", engine.Name)
}

// lastArgument is the SQL a planned command carries (the value after -c or -e).
func lastArgument(argv []string) string {
	if len(argv) == 0 {
		return ""
	}
	return argv[len(argv)-1]
}

func adminHost(resource Resource) string {
	if resource.AdminHost != "" {
		return resource.AdminHost
	}
	return "127.0.0.1"
}

func adminPort(resource Resource) int {
	if resource.AdminPort > 0 {
		return resource.AdminPort
	}
	return port(resource.Port, 6379)
}

// ParseRedisURL reads redis://[user][:password@]host[:port] into the parts the
// plans need.
func ParseRedisURL(raw string) (host string, port int, user string, secret string, err error) {
	raw = strings.TrimSpace(raw)
	if raw == "" {
		return "", 0, "", "", errors.New("dbengine: no Redis admin connection configured")
	}
	rest := raw
	if i := strings.Index(rest, "://"); i >= 0 {
		rest = rest[i+3:]
	}
	if at := strings.LastIndex(rest, "@"); at >= 0 {
		credentials := rest[:at]
		rest = rest[at+1:]
		if colon := strings.Index(credentials, ":"); colon >= 0 {
			user = credentials[:colon]
			secret = credentials[colon+1:]
		} else {
			secret = credentials
		}
	}
	if slash := strings.IndexAny(rest, "/?"); slash >= 0 {
		rest = rest[:slash]
	}
	host, portText := rest, ""
	if colon := strings.LastIndex(rest, ":"); colon >= 0 {
		host, portText = rest[:colon], rest[colon+1:]
	}
	if host == "" {
		host = "127.0.0.1"
	}
	port = 6379
	if portText != "" {
		value, convErr := strconv.Atoi(portText)
		if convErr != nil || value <= 0 || value > 65535 {
			return "", 0, "", "", fmt.Errorf("dbengine: %q is not a usable Redis port", portText)
		}
		port = value
	}
	return host, port, user, secret, nil
}

// ClientBinary is the CLI for this engine (mariadb's client when available).
func (r Resource) ClientBinary() string {
	if engine, ok := Lookup(r.Engine); ok && engine.Client != "" {
		return engine.Client
	}
	return "mysql"
}

func port(value, fallback int) int {
	if value > 0 {
		return value
	}
	return fallback
}

// quoteIdent quotes a PostgreSQL identifier, doubling embedded quotes.
func quoteIdent(name string) string {
	if strings.ContainsAny(name, `\x00`) {
		name = strings.ReplaceAll(name, "\x00", "")
	}
	return `"` + strings.ReplaceAll(name, `"`, `""`) + `"`
}

// quoteBacktick quotes a MySQL identifier.
func quoteBacktick(name string) string {
	return "`" + strings.ReplaceAll(name, "`", "``") + "`"
}

// quoteLiteral makes a value safe inside a single-quoted SQL literal: embedded
// quotes are doubled, which is how PostgreSQL escapes them. Nothing a client
// sends can therefore end the literal and start a statement of its own.
func quoteLiteral(value string) string {
	value = strings.ReplaceAll(value, "\x00", "")
	return "'" + strings.ReplaceAll(value, "'", "''") + "'"
}

// escapeSingleQuotes makes a value safe inside a single-quoted MySQL literal.
func escapeSingleQuotes(value string) string {
	value = strings.ReplaceAll(value, `\`, `\\`)
	return strings.ReplaceAll(value, `'`, `\'`)
}
